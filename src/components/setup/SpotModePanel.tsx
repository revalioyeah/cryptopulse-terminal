import { useEffect, useMemo, useState } from 'react';
import {
  AlertTriangle,
  Award,
  Layers,
  Rocket,
  Save,
  Send,
  ShieldCheck,
  Sparkles,
  Wallet,
} from 'lucide-react';
import type { Coin, DcaLayer, SpotSetup } from '../../types';
import { useBinanceKlinesQuery, useTop100TokenomicsQuery } from '../../hooks/useMarketQueries';
import { sendTelegramHtmlMessage } from '../../services/adapters/telegramAdapter';
import { detectSupportResistance } from '../../services/indicators';
import {
  SPOT_DCA_PROFILES,
  type SpotDcaProfileId,
  computeSpotTargetsAndMoonbag,
  evaluateSpotQuality,
  generateSpotDcaPlan,
} from '../../services/spotScoring';
import { useAppStore } from '../../store/useAppStore';
import { usePortfolioStore } from '../../store/usePortfolioStore';
import { useSettingsStore } from '../../store/useSettingsStore';
import { useTradingStore } from '../../store/useTradingStore';
import { formatPercent, formatPrice, formatQty, formatUsd, generateId } from '../../utils/format';
import { formatSpotSetupTelegram } from '../../utils/telegramFormatters';

export function SpotModePanel({ coin }: { coin: Coin }) {
  const coins = useAppStore((s) => s.coins);
  const pendingSetupDraft = useAppStore((s) => s.pendingSetupDraft);
  const clearPendingSetupDraft = useAppStore((s) => s.clearPendingSetupDraft);
  const pushToast = useAppStore((s) => s.pushToast);
  const openSettingsModal = useAppStore((s) => s.openSettingsModal);

  const addSpotSetup = useTradingStore((s) => s.addSpotSetup);
  const usdtCash = usePortfolioStore((s) => s.usdtBalance);
  const telegramConfig = useSettingsStore((s) => s.telegramConfig);

  const klines1dQuery = useBinanceKlinesQuery(coin.symbol, '1d', 200, coin.price);
  const klines4hQuery = useBinanceKlinesQuery(coin.symbol, '4h', 120, coin.price);
  const tokenomicsQuery = useTop100TokenomicsQuery(coins);

  const candles1d = klines1dQuery.data?.candles ?? [];
  const candles4h = klines4hQuery.data?.candles ?? [];

  const { coinTokenomics, btcBench7d, btcBench30d } = useMemo(() => {
    const recs = tokenomicsQuery.data?.records ?? [];
    const found = recs.find((r) => r.symbol === coin.symbol);
    const btc = recs.find((r) => r.symbol === 'BTCUSDT');
    return {
      coinTokenomics: found,
      btcBench7d: btc?.change7dPercent,
      btcBench30d: btc?.change30dPercent,
    };
  }, [tokenomicsQuery.data, coin.symbol]);

  const quality = useMemo(
    () =>
      evaluateSpotQuality(coin, candles1d, {
        tokenomics: coinTokenomics,
        btcBench7d,
        btcBench30d,
        h4Candles: candles4h,
      }),
    [coin, candles1d, candles4h, coinTokenomics, btcBench7d, btcBench30d],
  );

  const { supports, resistances } = useMemo(
    () => detectSupportResistance(candles1d),
    [candles1d],
  );

  const [dcaProfile, setDcaProfile] = useState<SpotDcaProfileId>('CONSERVATIVE');
  const [budgetUsdt, setBudgetUsdt] = useState<number>(1500);
  const [layerPrices, setLayerPrices] = useState<[number, number, number]>([
    Number((coin.price * 0.975).toPrecision(6)),
    Number((coin.price * 0.91).toPrecision(6)),
    Number((coin.price * 0.83).toPrecision(6)),
  ]);
  const [tp1, setTp1] = useState<number>(() => Number((coin.price * 1.25).toPrecision(6)));
  const [tp2, setTp2] = useState<number>(() => Number((coin.price * 1.65).toPrecision(6)));
  const [tp3, setTp3] = useState<number>(() => Number((coin.price * 2.45).toPrecision(6)));
  const [notes, setNotes] = useState('');

  const activeWeights = SPOT_DCA_PROFILES[dcaProfile].weights;

  const handleAutoGenerateDca = (profileOverride?: SpotDcaProfileId) => {
    const weights = SPOT_DCA_PROFILES[profileOverride ?? dcaProfile].weights;
    const plan = generateSpotDcaPlan(coin.price, budgetUsdt, supports, resistances, weights);
    setLayerPrices([plan.layers[0].price, plan.layers[1].price, plan.layers[2].price]);
    setTp1(plan.tp1);
    setTp2(plan.tp2);
    setTp3(plan.tp3);
    pushToast(
      `3-Layer DCA ${coin.baseAsset} Dibuat`,
      `Profil ${weights.join('/')} · Support 1D · Avg ${formatPrice(plan.projectedAvgEntry)}`,
      'success',
    );
  };

  // Re-initialize when selected coin or candles arrive
  useEffect(() => {
    const plan = generateSpotDcaPlan(coin.price, budgetUsdt, supports, resistances, activeWeights);
    setLayerPrices([plan.layers[0].price, plan.layers[1].price, plan.layers[2].price]);
    setTp1(plan.tp1);
    setTp2(plan.tp2);
    setTp3(plan.tp3);
  }, [coin.symbol, candles1d.length]); // eslint-disable-line react-hooks/exhaustive-deps

  // Consume optional draft from Scanner Pro Spot Funnel
  useEffect(() => {
    if (!pendingSetupDraft || pendingSetupDraft.mode !== 'SPOT' || pendingSetupDraft.symbol !== coin.symbol) {
      return;
    }
    if (pendingSetupDraft.tp1) setTp1(pendingSetupDraft.tp1);
    if (pendingSetupDraft.tp2) setTp2(pendingSetupDraft.tp2);
    if (pendingSetupDraft.tp3) setTp3(pendingSetupDraft.tp3);
    if (pendingSetupDraft.notes) setNotes(pendingSetupDraft.notes);
    clearPendingSetupDraft();
  }, [pendingSetupDraft, coin.symbol, clearPendingSetupDraft]);

  const layers: DcaLayer[] = useMemo(() => {
    const specs: Array<{ layer: 1 | 2 | 3; label: string; pct: number; price: number }> = [
      { layer: 1, label: 'Layer 1 (Entry Awal)', pct: activeWeights[0], price: Math.max(layerPrices[0], 1e-8) },
      { layer: 2, label: 'Layer 2 (Support Utama)', pct: activeWeights[1], price: Math.max(layerPrices[1], 1e-8) },
      { layer: 3, label: 'Layer 3 (Deep Value)', pct: activeWeights[2], price: Math.max(layerPrices[2], 1e-8) },
    ];
    return specs.map((s) => {
      const b = (budgetUsdt * s.pct) / 100;
      return {
        layer: s.layer,
        label: s.label,
        price: s.price,
        allocationPercent: s.pct,
        budgetUsdt: Number(b.toFixed(2)),
        estimatedQty: b / s.price,
      };
    });
  }, [budgetUsdt, layerPrices, activeWeights]);

  const plan = useMemo(
    () => computeSpotTargetsAndMoonbag(layers, budgetUsdt, tp1, tp2, tp3),
    [layers, budgetUsdt, tp1, tp2, tp3],
  );

  const buildSpotRecord = (): SpotSetup => ({
    id: generateId('spot'),
    symbol: coin.symbol,
    baseAsset: coin.baseAsset,
    budgetUsdt,
    qualityScore: quality.totalScore,
    tier: quality.tier,
    layers,
    projectedAvgEntry: plan.projectedAvgEntry,
    tp1,
    tp2,
    tp3,
    roiTp1Percent: plan.roiTp1Percent,
    roiTp2Percent: plan.roiTp2Percent,
    roiTp3Percent: plan.roiTp3Percent,
    sellPercentAtTp2ForBreakEven: plan.sellPercentAtTp2ForBreakEven,
    moonbagQty: plan.moonbagQty,
    moonbagValueAtTp3Usdt: plan.moonbagValueAtTp3Usdt,
    notes: notes.trim() || `Profil DCA ${activeWeights.join('/')} · Invalidation < ${formatPrice(plan.invalidationPrice)}`,
    status: 'Waiting',
    source: 'Manual',
    createdAt: Date.now(),
    updatedAt: Date.now(),
  });

  const handleSave = async () => {
    const rec = buildSpotRecord();
    addSpotSetup(rec);
    pushToast(
      `Setup Spot DCA ${rec.baseAsset} Disimpan`,
      `Budget ${formatUsd(rec.budgetUsdt)} · Tier ${rec.tier} (${rec.qualityScore}/100)`,
      'success',
    );
    if (telegramConfig.enabled && telegramConfig.autoSendSpot && telegramConfig.botToken && telegramConfig.chatId) {
      await sendTelegramHtmlMessage(telegramConfig, formatSpotSetupTelegram(rec));
    }
  };

  const handleSendTelegram = async () => {
    if (!telegramConfig.botToken || !telegramConfig.chatId) {
      pushToast('Telegram Belum Diatur', 'Isi Bot Token & Chat ID di Settings & Backup.', 'warning');
      openSettingsModal();
      return;
    }
    const res = await sendTelegramHtmlMessage(telegramConfig, formatSpotSetupTelegram(buildSpotRecord()));
    pushToast(
      res.ok ? 'Setup Spot Terkirim' : 'Gagal Kirim Telegram',
      res.message,
      res.ok ? 'success' : 'error',
    );
  };

  const tierStyle =
    quality.tier === 'Core'
      ? 'bg-[#00C087]/15 text-[#00C087] border-[#00C087]/40'
      : quality.tier === 'Growth'
        ? 'bg-[#F0B90B]/15 text-[#F0B90B] border-[#F0B90B]/40'
        : 'bg-[#F6465D]/15 text-[#F6465D] border-[#F6465D]/40';

  return (
    <div className="space-y-4">
      {/* Spot Quality Score (0-100) */}
      <section aria-label="Spot Quality Score" className="cp-card p-4">
        <div className="flex flex-wrap items-center justify-between gap-3 border-b border-[#2B3139] pb-3">
          <div className="flex items-start gap-2.5">
            <Award className="mt-0.5 h-5 w-5 shrink-0 text-[#F0B90B]" />
            <div>
              <div className="flex flex-wrap items-center gap-2">
                <h2 className="text-sm font-semibold text-[#EAECEF]">
                  Spot Quality Score — {coin.baseAsset} ({coin.name})
                </h2>
                {coinTokenomics && !coinTokenomics.isFallback && (
                  <span className="inline-flex items-center gap-1 rounded-full border border-[#00C087]/35 bg-[#00C087]/10 px-2 py-0.5 text-[10px] font-medium text-[#00C087]">
                    <ShieldCheck className="h-3 w-3" />
                    CoinGecko MCap/FDV + 1D/4H Live
                  </span>
                )}
              </div>
              <p className="mt-0.5 text-xs text-[#848E9C]">{quality.verdict}</p>
            </div>
          </div>

          <div className="flex items-center gap-2.5">
            <span className="font-mono tabular-nums text-2xl font-bold text-[#F0B90B]">
              {quality.totalScore}
              <span className="text-xs text-[#848E9C]">/100</span>
            </span>
            <span className={`rounded-lg border px-2.5 py-1 text-xs font-bold ${tierStyle}`}>
              Tier: {quality.tier}
            </span>
          </div>
        </div>

        <div className="mt-3 grid grid-cols-1 gap-2.5 sm:grid-cols-2 lg:grid-cols-4">
          {quality.pillars.map((pillar) => {
            const pct = Math.round((pillar.score / pillar.maxScore) * 100);
            const barColor = pct >= 72 ? 'bg-[#00C087]' : pct >= 52 ? 'bg-[#F0B90B]' : 'bg-[#F6465D]';
            return (
              <div
                key={pillar.name}
                className="rounded-xl border border-[#2B3139] bg-[#0B0E11] p-3"
              >
                <div className="flex items-center justify-between text-xs">
                  <span className="font-semibold text-[#EAECEF]">{pillar.name}</span>
                  <span className="font-mono tabular-nums font-bold text-[#F0B90B]">
                    {pillar.score}/{pillar.maxScore}
                  </span>
                </div>
                <div className="mt-2 h-1.5 w-full overflow-hidden rounded-full bg-[#1E2329]">
                  <div className={`h-full rounded-full ${barColor}`} style={{ width: `${pct}%` }} />
                </div>
                <p className="mt-2 text-[11px] leading-relaxed text-[#848E9C]">{pillar.note}</p>
              </div>
            );
          })}
        </div>
      </section>

      {/* 3-Layer DCA + Moonbag Planner */}
      <div className="grid grid-cols-1 gap-4 xl:grid-cols-12">
        <div className="cp-card space-y-4 p-4 xl:col-span-7">
          <div className="flex flex-wrap items-center justify-between gap-2">
            <div className="flex items-center gap-2">
              <Layers className="h-4 w-4 text-[#F0B90B]" />
              <h3 className="text-sm font-semibold text-[#EAECEF]">
                Smart 3-Layer DCA ({activeWeights.join('% / ')}%)
              </h3>
            </div>
            <button
              type="button"
              onClick={() => handleAutoGenerateDca()}
              className="inline-flex min-h-[40px] items-center gap-1.5 rounded-xl bg-[#F0B90B] px-3 text-xs font-semibold text-[#0B0E11] hover:bg-[#F0B90B]/90"
            >
              <Sparkles className="h-3.5 w-3.5" />
              Auto-Generate Support 1D
            </button>
          </div>

          {/* DCA Weight Profile Selector */}
          <div className="grid grid-cols-1 gap-2 sm:grid-cols-3">
            {(Object.keys(SPOT_DCA_PROFILES) as SpotDcaProfileId[]).map((pid) => {
              const prof = SPOT_DCA_PROFILES[pid];
              const active = dcaProfile === pid;
              return (
                <button
                  key={pid}
                  type="button"
                  onClick={() => {
                    setDcaProfile(pid);
                    handleAutoGenerateDca(pid);
                  }}
                  className={`min-h-[44px] rounded-xl border px-3 py-2 text-left transition ${
                    active
                      ? 'border-[#F0B90B] bg-[#F0B90B]/12 text-[#F0B90B]'
                      : 'border-[#2B3139] bg-[#0B0E11] text-[#848E9C] hover:text-[#EAECEF]'
                  }`}
                >
                  <span className="block text-xs font-semibold">{prof.label}</span>
                  <span className="block truncate text-[10px] opacity-80">{prof.desc}</span>
                </button>
              );
            })}
          </div>

          <div className="grid grid-cols-1 gap-3 sm:grid-cols-2">
            <div>
              <div className="mb-1 flex items-center justify-between gap-2">
                <label className="text-[11px] text-[#848E9C]">Total Budget Spot (USDT)</label>
                {usdtCash > 0 && (
                  <button
                    type="button"
                    onClick={() => setBudgetUsdt(Math.floor(usdtCash))}
                    className="inline-flex items-center gap-1 text-[10px] font-semibold text-[#00C087] hover:underline"
                  >
                    <Wallet className="h-3 w-3" />
                    Kas: {formatUsd(usdtCash)}
                  </button>
                )}
              </div>
              <input
                type="number"
                min={20}
                step={50}
                value={budgetUsdt}
                onChange={(e) => setBudgetUsdt(Math.max(10, Number(e.target.value) || 0))}
                className="font-mono tabular-nums min-h-[42px] w-full rounded-xl border border-[#2B3139] bg-[#0B0E11] px-3 text-sm font-bold text-[#F0B90B]"
              />
            </div>
            <div className="flex flex-col justify-center rounded-xl border border-[#2B3139] bg-[#0B0E11] px-3 py-2">
              <span className="text-[11px] text-[#848E9C]">Proyeksi Average Entry (All Filled)</span>
              <span className="font-mono tabular-nums text-base font-bold text-[#00C087]">
                {formatPrice(plan.projectedAvgEntry)}
              </span>
            </div>
          </div>

          {/* 3 Layers Editable */}
          <div className="space-y-2">
            {layers.map((layer, idx) => {
              const discPct =
                coin.price > 0 ? ((layer.price - coin.price) / coin.price) * 100 : 0;
              return (
                <div
                  key={layer.layer}
                  className="grid grid-cols-1 gap-2 rounded-xl border border-[#2B3139] bg-[#0B0E11] p-3 sm:grid-cols-12 sm:items-center"
                >
                  <div className="sm:col-span-4">
                    <span className="text-xs font-semibold text-[#EAECEF]">{layer.label}</span>
                    <p className="font-mono tabular-nums text-[11px] text-[#F0B90B]">
                      {layer.allocationPercent}% · {formatUsd(layer.budgetUsdt)}
                    </p>
                  </div>
                  <div className="sm:col-span-4">
                    <label className="mb-0.5 flex items-center justify-between text-[10px] text-[#5E6673]">
                      <span>Harga Beli</span>
                      <span className="font-mono tabular-nums text-[#848E9C]">
                        {formatPercent(discPct, 1)}
                      </span>
                    </label>
                    <input
                      type="number"
                      step="any"
                      value={layerPrices[idx]}
                      onChange={(e) => {
                        const next: [number, number, number] = [...layerPrices];
                        next[idx] = Number(e.target.value) || 0;
                        setLayerPrices(next);
                      }}
                      className="font-mono tabular-nums min-h-[40px] w-full rounded-lg border border-[#2B3139] bg-[#161A1E] px-2.5 text-xs font-semibold text-[#EAECEF]"
                    />
                  </div>
                  <div className="sm:col-span-4 sm:text-right">
                    <span className="block text-[10px] text-[#5E6673]">Est. Qty</span>
                    <span className="font-mono tabular-nums text-xs font-semibold text-[#EAECEF]">
                      {formatQty(layer.estimatedQty)} {coin.baseAsset}
                    </span>
                  </div>
                </div>
              );
            })}
          </div>

          {/* TP1 - TP3 */}
          <div className="grid grid-cols-1 gap-3 sm:grid-cols-3">
            {[
              { label: 'TP1', val: tp1, set: setTp1, roi: plan.roiTp1Percent, profit: plan.profitTp1Usdt },
              { label: 'TP2 (Balik Modal)', val: tp2, set: setTp2, roi: plan.roiTp2Percent, profit: plan.profitTp2Usdt },
              { label: 'TP3 (Moonbag)', val: tp3, set: setTp3, roi: plan.roiTp3Percent, profit: plan.profitTp3Usdt },
            ].map((t) => (
              <div key={t.label} className="rounded-xl border border-[#2B3139] bg-[#0B0E11] p-2.5">
                <div className="mb-1 flex items-center justify-between text-[11px]">
                  <span className="font-semibold text-[#EAECEF]">{t.label}</span>
                  <span className="font-mono tabular-nums font-bold text-[#00C087]">
                    {formatPercent(t.roi, 1)}
                  </span>
                </div>
                <input
                  type="number"
                  step="any"
                  value={t.val}
                  onChange={(e) => t.set(Number(e.target.value) || 0)}
                  className="font-mono tabular-nums min-h-[40px] w-full rounded-lg border border-[#2B3139] bg-[#161A1E] px-2.5 text-xs font-semibold text-[#00C087]"
                />
                <span className="font-mono tabular-nums mt-1 block text-[10px] text-[#848E9C]">
                  Est. Profit: {formatUsd(t.profit, true)}
                </span>
              </div>
            ))}
          </div>

          <textarea
            rows={2}
            value={notes}
            onChange={(e) => setNotes(e.target.value)}
            placeholder="Catatan akumulasi jangka menengah / katalis..."
            className="w-full rounded-xl border border-[#2B3139] bg-[#0B0E11] p-2.5 text-xs text-[#EAECEF] placeholder-[#5E6673]"
          />
        </div>

        {/* Right: Moonbag / Balik Modal Planner */}
        <div className="cp-card flex flex-col justify-between p-4 xl:col-span-5">
          <div className="space-y-3">
            <div className="flex items-center gap-2 border-b border-[#2B3139] pb-3">
              <Rocket className="h-4 w-4 text-[#F0B90B]" />
              <h3 className="text-sm font-semibold text-[#EAECEF]">
                Moonbag &amp; Balik Modal Planner
              </h3>
            </div>

            <div className="rounded-xl border border-[#00C087]/30 bg-[#00C087]/8 p-3.5">
              <span className="text-[11px] font-medium text-[#848E9C]">
                Persentase Jual di TP2 agar 100% Modal Awal Kembali ke USDT
              </span>
              <p className="font-mono tabular-nums mt-1 text-3xl font-bold text-[#00C087]">
                {plan.sellPercentAtTp2ForBreakEven.toFixed(1)}%
              </p>
              <p className="font-mono tabular-nums mt-1 text-xs text-[#EAECEF]">
                Jual {formatQty(plan.qtySoldAtTp2)} {coin.baseAsset} @ {formatPrice(tp2)} ={' '}
                <strong className="text-[#F0B90B]">{formatUsd(budgetUsdt)}</strong> kembali aman.
              </p>
            </div>

            <div className="grid grid-cols-2 gap-2.5">
              <div className="rounded-xl border border-[#2B3139] bg-[#0B0E11] p-3">
                <span className="text-[11px] text-[#848E9C]">Sisa Coin Moonbag</span>
                <p className="font-mono tabular-nums mt-1 text-base font-bold text-[#EAECEF]">
                  {formatQty(plan.moonbagQty)} {coin.baseAsset}
                </p>
                <span className="font-mono tabular-nums text-[10px] text-[#00C087]">
                  {(100 - plan.sellPercentAtTp2ForBreakEven).toFixed(1)}% Risk-Free
                </span>
              </div>

              <div className="rounded-xl border border-[#2B3139] bg-[#0B0E11] p-3">
                <span className="text-[11px] text-[#848E9C]">Est. Nilai Moonbag @ TP3</span>
                <p className="font-mono tabular-nums mt-1 text-base font-bold text-[#F0B90B]">
                  {formatUsd(plan.moonbagValueAtTp3Usdt)}
                </p>
                <span className="text-[10px] text-[#848E9C]">Pure Profit Gratis</span>
              </div>
            </div>

            {/* Structural Invalidation Reference */}
            <div className="flex items-start gap-2 rounded-xl border border-[#F6465D]/30 bg-[#F6465D]/8 p-3 text-xs">
              <AlertTriangle className="mt-0.5 h-4 w-4 shrink-0 text-[#F6465D]" />
              <div>
                <span className="font-semibold text-[#EAECEF]">
                  Batas Invalidasi Struktur (1D Close):{' '}
                  <span className="font-mono tabular-nums text-[#F6465D]">
                    &lt; {formatPrice(plan.invalidationPrice)}
                  </span>
                </span>
                <p className="mt-0.5 text-[11px] text-[#848E9C]">
                  Jika candle harian tutup di bawah zona ini, hentikan DCA tambahan &amp; evaluasi ulang tesis fundamental.
                </p>
              </div>
            </div>

            <div className="rounded-xl border border-[#2B3139] bg-[#0B0E11] p-3 text-xs leading-relaxed text-[#848E9C]">
              Total estimasi coin jika seluruh 3 layer terisi:{' '}
              <strong className="font-mono tabular-nums text-[#EAECEF]">
                {formatQty(plan.totalEstimatedQty)} {coin.baseAsset}
              </strong>{' '}
              pada rata-rata beli{' '}
              <strong className="font-mono tabular-nums text-[#EAECEF]">
                {formatPrice(plan.projectedAvgEntry)}
              </strong>
              .
            </div>
          </div>

          <div className="mt-4 grid grid-cols-1 gap-2 sm:grid-cols-2">
            <button
              type="button"
              onClick={() => void handleSave()}
              className="inline-flex min-h-[44px] items-center justify-center gap-2 rounded-xl bg-[#F0B90B] px-4 text-xs font-bold text-[#0B0E11] transition hover:bg-[#F0B90B]/90"
            >
              <Save className="h-4 w-4" />
              Simpan Setup Spot
            </button>
            <button
              type="button"
              onClick={() => void handleSendTelegram()}
              className="inline-flex min-h-[44px] items-center justify-center gap-2 rounded-xl border border-[#2B3139] bg-[#1E2329] px-4 text-xs font-semibold text-[#EAECEF] transition hover:border-[#F0B90B]/60 hover:text-[#F0B90B]"
            >
              <Send className="h-4 w-4" />
              Kirim Telegram
            </button>
          </div>
        </div>
      </div>
    </div>
  );
}
